#!/bin/bash
# Operator end-to-end check of macOS build disks. Run it on the macOS VM host,
# as an account that can submit jobs, after installing a runner and an image
# whose guest agent speaks macOS protocol version 2:
#
#   script/macos-runner/build-disk-e2e.sh <new checkout under /Users> [<runner state root>]
#
# It creates a small Cargo checkout at the given path, which must not exist yet,
# and runs two jobs on it through `ck motor run --platform macos`
# (MOTOR_CK names another client binary). It proves:
#
# 1. The first job sees target/ as a separate APFS volume, mounted
#    nosuid,nodev, owned by the job account: the agent found the build disk,
#    formatted it and mounted it. Cargo compiles the crate there, and a file
#    returned from target/ is installed in this checkout with the hash the job
#    printed.
# 2. The second job finds the first job's marker and Cargo compiles nothing:
#    the runner published the first job's disk and attached a clone of it.
#    Neither job printed the "reformatted" notice.
# 3. With the state root, the kept targets/<key>.img is exactly 128 GiB and
#    sparse, and no old targets/<key> folder remains.
#
# Each job's JSONL record is kept in <checkout>.evidence. The script exits
# non-zero at the first failed check.
set -euo pipefail

if [[ $# -lt 1 || $# -gt 2 ]]; then
  echo "usage: $0 <new checkout under /Users> [<runner state root>]" >&2
  exit 2
fi
checkout=$1
state=${2:-}
ck=${MOTOR_CK:-ck}
case "$checkout" in
  /Users/*) ;;
  *) echo "the checkout must be an absolute path under /Users" >&2; exit 2 ;;
esac
if [[ -e "$checkout" ]]; then
  echo "$checkout already exists; name a new directory" >&2
  exit 2
fi
evidence="$checkout.evidence"
mkdir -p "$checkout/src" "$evidence"
fail() { echo "FAIL: $*" >&2; exit 1; }
pass() { echo "ok: $*"; }

cat >"$checkout/Cargo.toml" <<'EOF'
[package]
name = "buildcheck"
version = "0.1.0"
edition = "2021"
EOF
cat >"$checkout/Cargo.lock" <<'EOF'
# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "buildcheck"
version = "0.1.0"
EOF
cat >"$checkout/src/main.rs" <<'EOF'
fn main() {
    println!("build disk check");
}
EOF
printf 'target/\n' >"$checkout/.gitignore"
git -C "$checkout" init -q
git -C "$checkout" add .
git -C "$checkout" -c user.name=e2e -c user.email=e2e@example.invalid commit -qm "build disk check"

run_job() {
  local name=$1
  shift
  local status=0
  "$ck" motor run --platform macos --cwd "$checkout" \
    --record-file "$evidence/$name.jsonl" "$@" \
    >"$evidence/$name.stdout" 2>"$evidence/$name.stderr" || status=$?
  cat "$evidence/$name.stdout"
  cat "$evidence/$name.stderr" >&2
  if grep -q "build disk could not be used" "$evidence/$name.stderr"; then
    fail "$name: the agent reformatted the build disk"
  fi
  [[ $status -eq 0 ]] || fail "$name: job exited with status $status"
}

# The mount table line for target/ looks like
# "/dev/disk5s1 on /Users/x/checkout/target (apfs, local, nodev, nosuid, ...)".
# The job's shell expands these scripts, not this one.
# shellcheck disable=SC2016
first_command='set -eu
line=$(mount | grep -F " on $PWD/target (")
echo "mount: $line"
case "$line" in *"(apfs,"*) ;; *) echo "target is not an APFS volume" >&2; exit 1 ;; esac
case "$line" in *nosuid*) ;; *) echo "target is not nosuid" >&2; exit 1 ;; esac
case "$line" in *nodev*) ;; *) echo "target is not nodev" >&2; exit 1 ;; esac
test "$(stat -f %d target)" != "$(stat -f %d .)"
test "$(stat -f %u target)" = "$(id -u)"
test ! -e target/e2e-marker
cargo build 2>build.log || { cat build.log >&2; exit 1; }
cat build.log >&2
grep -q "Compiling buildcheck" build.log
echo first >target/e2e-marker
echo "sha256: $(shasum -a 256 target/debug/buildcheck | cut -d" " -f1)"'
run_job first --return-path "$checkout/target/debug/buildcheck" -- bash -c "$first_command"
pass "first job: target/ is a separate APFS volume, nosuid,nodev, owned by the job, and Cargo built there"
hash=$(sed -n 's/^sha256: //p' "$evidence/first.stdout")
[[ -n "$hash" ]] || fail "first job printed no hash"
returned="$checkout/target/debug/buildcheck"
[[ -f "$returned" ]] || fail "the file returned from target/ was not installed at $returned"
[[ "$(shasum -a 256 "$returned" | cut -d" " -f1)" == "$hash" ]] ||
  fail "the returned file's hash differs from the one the job printed"
pass "first job: the file returned from target/ carries the hash the job printed"

# shellcheck disable=SC2016
second_command='set -eu
test "$(cat target/e2e-marker)" = first
cargo build 2>build.log || { cat build.log >&2; exit 1; }
cat build.log >&2
if grep -q Compiling build.log; then echo "Cargo rebuilt on a warm disk" >&2; exit 1; fi'
run_job second -- bash -c "$second_command"
pass "second job: the first job's volume came back and Cargo compiled nothing"

if [[ -n "$state" ]]; then
  lower=$(printf %s "$checkout" | tr '[:upper:]' '[:lower:]')
  key=$(printf %s "$lower" | shasum -a 256 | cut -d" " -f1)
  image="$state/targets/$key.img"
  [[ -f "$image" ]] || fail "no kept build disk at $image"
  size=$(stat -f %z "$image")
  [[ "$size" -eq 137438953472 ]] || fail "$image is $size bytes, not 128 GiB"
  allocated=$(( $(stat -f %b "$image") * 512 ))
  [[ "$allocated" -lt "$size" ]] || fail "$image is not sparse"
  [[ ! -e "$state/targets/$key" ]] || fail "the old build folder $state/targets/$key remains"
  pass "kept build disk $image: 128 GiB, $allocated bytes allocated"
fi
echo "all build disk checks passed; evidence in $evidence"
