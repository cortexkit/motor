def write_bytes(path, data):
    global FILE_COUNT
    FILE_COUNT += 1
    if CHECK_MODE:
        if not path.is_file() or path.read_bytes() != data:
            raise SystemExit(f"exec-remote/v1 --check: stale or missing {path.relative_to(ROOT)}")
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)


def emit(folder, name, value):
    stem = ROOT / folder / name
    # All keys/strings are ASCII and all numbers are small integers; sorted JSON
    # is RFC 8785 within this deliberately restricted vector domain.
    jcs = json.dumps(value, sort_keys=True, ensure_ascii=False,
                     separators=(",", ":")).encode("utf-8")
    write_bytes(stem.with_suffix(".json"), (json.dumps(value, indent=2) + "\n").encode("utf-8"))
    write_bytes(stem.with_suffix(".jcs"), jcs)
    write_bytes(stem.with_suffix(".sha256"), hashlib.sha256(jcs).hexdigest().encode())


def terminal(outcome, ran: Optional[str] = "remote", tree_hash: Optional[str] = TREE, **extra):
    return {"type": "terminal", "job_id": JOB, "outcome": outcome,
            "wall_ms": 125 if ran == "remote" else 0, "queue_wait_ms": 25,
            "bundle_bytes": sum(len(data) for data in PAYLOADS), "ran": ran,
            "tree_hash": tree_hash,
            "workspace_changes": ["result.txt"] if ran == "remote" else None,
            **extra}


def upload(start, accepted, end):
    return [start, accepted, *[frame for chunk in CHUNKS
                             for frame in (chunk, HEARTBEAT)], end]


