async fn old_dated_change(without_times: bool) {
    let (f, mut config, base) = fixture();
    save(&f.main, "leaf/src/watched/value", "old-dated change\n");
    git(&f.main, &["add", "-A"]);
    let result = Command::new("git")
        .arg("-C")
        .arg(&f.main)
        .env("GIT_AUTHOR_DATE", "2000-01-01T00:00:00Z")
        .env("GIT_COMMITTER_DATE", "2000-01-01T00:00:00Z")
        .args([
            "-c",
            "user.name=Test",
            "-c",
            "user.email=test@example.invalid",
            "commit",
            "-m",
            "old change",
        ])
        .output()
        .unwrap();
    assert!(result.status.success(), "{result:?}");
    let changed = git(&f.main, &["rev-parse", "HEAD"]);
    assert_eq!(
        git(&f.main, &["show", "-s", "--format=%ct", "HEAD"]),
        "946684800"
    );
    // Populate before the fill, so disabling the time step really leaves a
    // changed source older than Cargo's copied dep-info, not a fresh checkout.
    config.disable_warm_builds = true;
    let runner = base_store_runner(config.clone());
    run(&f, &runner, "old-dated", "true").await;
    drop(runner);
    evict_unbuilt_target(&f, "old-dated");
    let path = f
        .scratch
        .join("remote/worktrees/old-dated/leaf/src/watched/value");
    let old = UNIX_EPOCH + Duration::from_secs(946684800);
    fs::File::open(&path)
        .unwrap()
        .set_times(fs::FileTimes::new().set_modified(old))
        .unwrap();
    git(&f.main, &["reset", "--hard", &base]);
    config.disable_warm_builds = false;
    config.seed_without_times = without_times;
    let runner = base_store_runner(config);
    let current = fill(&f, &runner).await;
    let record: crate::build_base::Record = read_json(&current.join("base.json")).unwrap();
    assert!(fs::metadata(&path).unwrap().mtime() < record.fill_start.seconds);
    git(&f.main, &["reset", "--hard", &changed]);
    if without_times {
        let (id, output) = run(&f, &runner, "old-dated", BUILD).await;
        assert_build(&runner, id, &output, &[], true);
        let assertion = std::panic::catch_unwind(|| {
            assert_eq!(
                artifacts(&output),
                REBUILT.iter().map(|s| (*s).to_owned()).collect(),
                "changed source was incorrectly reused"
            )
        });
        assert!(
            assertion.is_err(),
            "the positive rebuild assertion must fail without the time step"
        );
    } else {
        three_builds(&f, &runner, "old-dated", REBUILT).await;
    }
}

