const BUILD: &str = r#"seed_probe() {
    printf 'seed proof phase=%s cwd=%s build-dir=%s target=%s\n' "$1" "$PWD" "$CARGO_BUILD_BUILD_DIR" "$CARGO_TARGET_DIR"
    printf 'seed proof physical-cwd='; readlink /proc/self/cwd
    printf 'seed proof bd-entry=%s\n' "$CARGO_TARGET_DIR"/bd/*
    printf 'seed proof wrapper=%s rustflags=%s incremental=%s encoded=%s\n' "${RUSTC_WRAPPER-unset}" "${RUSTFLAGS-unset}" "${CARGO_INCREMENTAL-unset}" "${CARGO_ENCODED_RUSTFLAGS-unset}"
    stat -c 'seed proof source %y %n' stable/src/lib.rs stable/src stable/Cargo.toml
    if test -d "$CARGO_TARGET_DIR/bd"; then
        find "$CARGO_TARGET_DIR/bd" -type d -path '*/.fingerprint/seed-stable-*' -exec sh -c '
            for folder do
                printf "seed proof fingerprint=%s\n" "$folder"
                ls -la "$folder"
                for file in "$folder"/lib-seed_stable "$folder"/lib-seed_stable.json; do
                    test ! -f "$file" || { printf "seed proof contents=%s\n" "$file"; cat "$file"; printf "\n"; }
                done
                stat -c "seed proof dep-info %y %n" "$folder"/dep-lib-seed_stable "$folder"/invoked.timestamp
            done
        ' sh {} +
        find "$CARGO_TARGET_DIR/bd" -type f -name 'seed_stable-*.d' -exec stat -c 'seed proof rustc-dep-info %y %n' {} +
    fi
}
seed_probe before
CARGO_LOG=cargo::core::compiler::fingerprint=info cargo build -vv --workspace --locked --offline --message-format=json
result=$?
seed_probe after
test "$result" -eq 0"#;
const REBUILT: &[&str] = &["seed-dependent", "seed-leaf"];

fn save(root: &Path, name: &str, bytes: &str) {
    let path = root.join(name);
    fs::create_dir_all(path.parent().unwrap()).unwrap();
    fs::write(path, bytes).unwrap();
}

fn snapshot(f: &Fixture) -> String {
    git(&f.main, &["add", "-A"]);
    git(
        &f.main,
        &[
            "-c",
            "user.name=Test",
            "-c",
            "user.email=test@example.invalid",
            "commit",
            "-m",
            "seed fixture",
        ],
    );
    git(&f.main, &["rev-parse", "HEAD"])
}

fn fixture() -> (Fixture, Config, String) {
    assert_eq!(unsafe { libc::geteuid() }, 0, "operator-only fixture");
    let f = Fixture::new();
    // This check precedes any fill or seed: a cold fallback is not a warm proof.
    let mut config = base_store_config(&f, BUILD);
    config.after_seed = Some(Arc::new(|target| {
        host_layout("after seed, before build-dir prepare", target);
        Ok(())
    }));
    config.before_seed_launch = Some(Arc::new(|cwd| {
        host_layout("after sandbox prepare, before launch", &cwd.join("target"));
        Ok(())
    }));
    let probe = config
        .state_dir()
        .join(format!("seed-device-{}", Uuid::now_v7()));
    fs::create_dir(&probe).unwrap();
    fs::write(probe.join("artifact"), b"same-device reflink").unwrap();
    let copy = config.workspace_roots[0].join(format!("seed-probe-{}", Uuid::now_v7()));
    platform::clone_target(&probe, &copy).expect("state-to-workspace reflink required");
    assert_eq!(
        fs::read(copy.join("artifact")).unwrap(),
        b"same-device reflink"
    );
    fs::remove_dir_all(probe).unwrap();
    fs::remove_dir_all(copy).unwrap();

    save(&f.main, ".gitignore", "/target/\n**/ignored\n");
    save(
        &f.main,
        "Cargo.toml",
        "[workspace]\nmembers = [\"leaf\", \"dependent\", \"stable\"]\nresolver = \"2\"\n",
    );
    save(&f.main, "Cargo.lock", "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"seed-dependent\"\nversion = \"0.1.0\"\ndependencies = [\n \"seed-leaf\",\n]\n\n[[package]]\nname = \"seed-leaf\"\nversion = \"0.1.0\"\n\n[[package]]\nname = \"seed-stable\"\nversion = \"0.1.0\"\n");
    for name in ["leaf", "dependent", "stable"] {
        save(
            &f.main,
            &format!("{name}/Cargo.toml"),
            &format!(
                "[package]\nname = \"seed-{name}\"\nversion = \"0.1.0\"\nedition = \"2021\"\n{}",
                if name == "dependent" {
                    "[dependencies]\nseed-leaf = { path = \"../leaf\" }\n"
                } else {
                    ""
                }
            ),
        );
    }
    save(
        &f.main,
        "leaf/src/lib.rs",
        "pub fn value() -> &'static str { include_str!(\"watched/value\") }\n",
    );
    save(&f.main, "leaf/src/watched/value", "base\n");
    save(&f.main, "leaf/src/watched/remove", "remove me\n");
    save(
        &f.main,
        "leaf/build.rs",
        r#"fn main() {
    println!("cargo:rerun-if-changed=src/watched");
    let path = std::path::PathBuf::from(std::env::var_os("OUT_DIR").unwrap()).join("runs");
    let old = std::fs::read_to_string(&path).unwrap_or_default().parse::<u32>().unwrap_or(0);
    std::fs::write(path, (old + 1).to_string()).unwrap();
}
"#,
    );
    save(
        &f.main,
        "dependent/src/lib.rs",
        "pub fn value() -> &'static str { seed_leaf::value() }\n",
    );
    save(
        &f.main,
        "stable/src/lib.rs",
        "pub fn value() -> u32 { 42 }\n",
    );
    let base = snapshot(&f);
    (f, config, base)
}

fn request(f: &Fixture, key: &str, command: &str) -> (Run, Vec<Vec<u8>>) {
    let (mut run, mut bytes) = f.run_worktree(command);
    run.siblings.clear();
    run.bundles.truncate(1);
    bytes.truncate(1);
    run.workspace_key = f
        .scratch
        .join(format!("remote/worktrees/{key}"))
        .display()
        .to_string();
    run.cwd = run.workspace_key.clone();
    (run, bytes)
}

async fn run(f: &Fixture, runner: &Runner, key: &str, command: &str) -> (Uuid, String) {
    let (run, bytes) = request(f, key, command);
    let id = run.job_id;
    f.submit(runner, &run, &bytes);
    drive_base_store(runner, || {
        runner.core.inner.lock().unwrap().jobs[&id]
            .terminal
            .is_some()
    })
    .await;
    let output = job_output(runner, id);
    assert_eq!(
        runner.core.inner.lock().unwrap().jobs[&id]
            .terminal
            .as_ref()
            .unwrap()
            .outcome,
        Outcome::Exit { code: 0 },
        "{output}"
    );
    (id, output)
}

async fn fill(f: &Fixture, runner: &Runner) -> PathBuf {
    let job = settle_base_store(f, runner).await;
    eprintln!(
        "base fill {} Cargo diagnostics:\n{}",
        job.id,
        job_output(runner, job.id)
    );
    assert_eq!(
        job.terminal.unwrap().outcome,
        Outcome::Exit { code: 0 },
        "{}",
        job_output(runner, job.id)
    );
    let current =
        crate::build_base::repository_store(&runner.config().state_dir(), &f.root).join("current");
    assert!(
        current.join("base.json").is_file(),
        "fill must publish, not silently build cold"
    );
    host_layout("published base", &current.join("target"));
    current
}

fn host_layout(label: &str, target: &Path) {
    fn walk(label: &str, path: &Path) {
        for entry in fs::read_dir(path).unwrap() {
            let entry = entry.unwrap();
            if entry.file_type().unwrap().is_dir() {
                eprintln!("seed host {label}: {}", entry.path().display());
                walk(label, &entry.path());
            } else if entry
                .path()
                .extension()
                .is_some_and(|extension| extension == "d")
            {
                eprintln!(
                    "seed host {label} dep-info {}: {}",
                    entry.path().display(),
                    fs::read_to_string(entry.path()).unwrap()
                );
            }
        }
    }
    let bd = target.join("bd");
    eprintln!("seed host {label} target={}", target.display());
    if bd.is_dir() {
        walk(label, &bd);
    }
}

fn artifacts(output: &str) -> BTreeSet<String> {
    output
        .lines()
        .filter_map(|line| {
            let value: serde_json::Value = serde_json::from_str(line).ok()?;
            if value["reason"] != "compiler-artifact" || value["fresh"] != false {
                return None;
            }
            let manifest = PathBuf::from(value["manifest_path"].as_str()?);
            Some(format!(
                "seed-{}",
                manifest.parent()?.file_name()?.to_str()?
            ))
        })
        .collect()
}

fn assert_build(runner: &Runner, id: Uuid, output: &str, expected: &[&str], seeded: bool) {
    let log = runner.job_log(id);
    let build = log.seed_build.lock().unwrap();
    assert_eq!(
        build.is_some(),
        seeded,
        "seeded state must reach launch: {output}"
    );
    assert!(
        output
            .lines()
            .any(|line| serde_json::from_str::<serde_json::Value>(line)
                .is_ok_and(|v| v["reason"] == "build-finished" && v["success"] == true)),
        "no completed Cargo build: {output}"
    );
    assert_eq!(
        artifacts(output),
        expected.iter().map(|s| (*s).to_owned()).collect(),
        "{output}"
    );
    if seeded {
        assert_eq!(
            build.as_ref().unwrap().count(),
            Some(expected.len()),
            "persisted Cargo output must produce the actual logged count"
        );
        // Feed actual captured Cargo output, after the same path rewrite as replay.
        let request = runner.core.inner.lock().unwrap().jobs[&id]
            .request
            .clone()
            .unwrap();
        let mut observer =
            super::super::seed_build_log::FirstBuild::new(request.workspace_key.into());
        assert_eq!(observer.push(output.as_bytes()), Some(expected.len()));
    }
}

fn script_runs(workspace: &Path) -> u32 {
    fn walk(path: &Path) -> Option<u32> {
        for entry in fs::read_dir(path).unwrap() {
            let entry = entry.unwrap();
            if entry.file_type().unwrap().is_dir() {
                if let Some(runs) = walk(&entry.path()) {
                    return Some(runs);
                }
            } else if entry.file_name() == "runs" {
                return Some(fs::read_to_string(entry.path()).unwrap().parse().unwrap());
            }
        }
        None
    }
    walk(&workspace.join("target")).expect("build script run counter")
}

async fn three_builds(f: &Fixture, runner: &Runner, key: &str, expected: &[&str]) {
    for (index, want) in [expected, &[], &[]].into_iter().enumerate() {
        let (id, output) = run(f, runner, key, BUILD).await;
        assert_build(runner, id, &output, want, index == 0);
    }
}

