#[tokio::test]
#[ignore = "requires root, systemd, motor-cache/motor-job accounts and reflink scratch"]
async fn isolated_seed_dates_tracked_symlink_without_touching_its_target() {
    let (f, config, _) = fixture();
    let outside = f.scratch.join("symlink-target");
    fs::write(&outside, b"not part of the checkout").unwrap();
    let target_time = UNIX_EPOCH + Duration::from_secs(1234567890);
    fs::File::open(&outside)
        .unwrap()
        .set_times(fs::FileTimes::new().set_modified(target_time))
        .unwrap();
    symlink(&outside, f.main.join("stable/linked")).unwrap();
    snapshot(&f);
    let before = mtime(&outside);
    let runner = base_store_runner(config);
    let current = fill(&f, &runner).await;
    let record: crate::build_base::Record = read_json(&current.join("base.json")).unwrap();
    let (id, output) = run(&f, &runner, "symlink", BUILD).await;
    assert_build(&runner, id, &output, &[], true);
    let link = f.scratch.join("remote/worktrees/symlink/stable/linked");
    assert!(fs::symlink_metadata(&link)
        .unwrap()
        .file_type()
        .is_symlink());
    assert_eq!(
        mtime(&link),
        (record.fill_start.seconds, record.fill_start.nanos)
    );
    assert_eq!(mtime(&outside), before);
}
