fn mtime(path: &Path) -> (i64, i64) {
    let metadata = fs::symlink_metadata(path).unwrap();
    (metadata.mtime(), metadata.mtime_nsec())
}

async fn rematerialized(changed: bool) {
    let (f, mut config, _) = fixture();
    let observed = Arc::new(Mutex::new(None));
    config.before_seed_launch = Some({
        let observed = observed.clone();
        Arc::new(move |cwd| {
            let source = cwd.join("leaf/src/watched/value");
            let parent = source.parent().unwrap();
            let original = (fs::metadata(&source)?.ino(), mtime(&source), mtime(parent));
            fs::hard_link(&source, cwd.join("target/rematerialized-alias"))?;
            *observed.lock().unwrap() = Some(original);
            Ok(())
        })
    });
    let runner = base_store_runner(config);
    fill(&f, &runner).await;
    if changed {
        save(
            &f.main,
            "leaf/src/watched/value",
            "changed before rematerialization\n",
        );
        snapshot(&f);
    }
    let (id, output) = run(&f, &runner, "rematerialized", BUILD).await;
    assert_build(
        &runner,
        id,
        &output,
        if changed { REBUILT } else { &[] },
        true,
    );
    let (inode, file_time, parent_time) = observed.lock().unwrap().unwrap();
    let workspace = f.scratch.join("remote/worktrees/rematerialized");
    let source = workspace.join("leaf/src/watched/value");
    assert_ne!(
        fs::metadata(&source).unwrap().ino(),
        inode,
        "launch must really rematerialize the tracked file"
    );
    assert_eq!(mtime(&source), file_time);
    assert_eq!(mtime(source.parent().unwrap()), parent_time);
    assert_eq!(script_runs(&workspace), if changed { 2 } else { 1 });
    let (id, output) = run(&f, &runner, "rematerialized", BUILD).await;
    assert_build(&runner, id, &output, &[], false);
}

