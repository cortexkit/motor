use super::*;

fn dependency_free_package(f: &Fixture, metadata: &str) {
    fs::create_dir_all(f.main.join("src")).unwrap();
    fs::write(f.main.join("src/lib.rs"), "pub fn value() {}\n").unwrap();
    fs::write(f.main.join("Cargo.lock"), "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"command-selection\"\nversion = \"0.1.0\"\n").unwrap();
    declare(
        f,
        &format!(
            "[package]\nname='command-selection'\nversion='0.1.0'\nedition='2021'\n{metadata}"
        ),
    );
}

fn writers(runner: &Runner) -> Vec<Job> {
    runner
        .core
        .inner
        .lock()
        .unwrap()
        .jobs
        .values()
        .filter(|job| job.base)
        .cloned()
        .collect()
}

#[tokio::test]
async fn dependency_free_default_command_records_success_without_writer() {
    let f = Fixture::new();
    dependency_free_package(&f, "");
    let mut config = f.config();
    config.base_commands.clear();
    let runner = Runner::open(config).unwrap();
    warm(&f, &runner).await;
    assert!(
        writers(&runner).is_empty(),
        "default dependency-free graph dispatched a writer"
    );
    let status = &runner.status().repositories[0];
    assert_eq!(
        status.published_commit,
        Some(git(&f.main, &["rev-parse", "HEAD"]))
    );
    assert_eq!(status.last_rebuild_result, Some(RebuildResult::Ok));
    assert_eq!(status.warm_target_age_s, Some(0));
}

#[tokio::test]
async fn dependency_free_explicit_config_command_runs_writer() {
    let f = Fixture::new();
    dependency_free_package(&f, "");
    let mut config = f.config();
    config.base_commands = vec!["printf configured > command-marker".into()];
    let runner = Runner::open(config).unwrap();
    warm(&f, &runner).await;
    let jobs = writers(&runner);
    assert_eq!(jobs.len(), 1, "explicit command was silently skipped");
    let checkout = Path::new(&jobs[0].request.as_ref().unwrap().cwd);
    assert_eq!(
        fs::read(checkout.join("command-marker")).unwrap(),
        b"configured"
    );
    assert_eq!(
        runner.status().repositories[0].last_rebuild_result,
        Some(RebuildResult::Ok)
    );
}

#[tokio::test]
async fn dependency_free_repository_declared_command_runs_writer() {
    for section in ["package", "workspace"] {
        let f = Fixture::new();
        dependency_free_package(&f, &format!("[{section}.metadata.motor]\nwarm-commands = ['printf declared > command-marker']\n"));
        let mut config = f.config();
        config.base_commands.clear();
        let runner = Runner::open(config).unwrap();
        warm(&f, &runner).await;
        let jobs = writers(&runner);
        assert_eq!(jobs.len(), 1, "{section} command was silently skipped");
        let checkout = Path::new(&jobs[0].request.as_ref().unwrap().cwd);
        assert_eq!(
            fs::read(checkout.join("command-marker")).unwrap(),
            b"declared"
        );
        assert_eq!(
            runner.status().repositories[0].last_rebuild_result,
            Some(RebuildResult::Ok)
        );
    }
}

#[tokio::test]
async fn explicit_default_command_does_not_reuse_a_record_with_no_writer() {
    let f = Fixture::new();
    dependency_free_package(&f, "");
    let mut config = f.config();
    config.base_commands.clear();
    let runner = Runner::open(config.clone()).unwrap();
    warm(&f, &runner).await;
    assert!(writers(&runner).is_empty());
    drop(runner);
    config.base_commands = vec!["cargo build --workspace --all-targets".into()];
    let runner = reopen(config);
    until(|| !writers(&runner).is_empty()).await;
    base_done(&runner).await;
    assert_eq!(writers(&runner).len(), 1);
    assert_eq!(
        runner.status().repositories[0].last_rebuild_result,
        Some(RebuildResult::Ok)
    );
    assert!(
        runner.core.inner.lock().unwrap().catalog.repositories[&f.root]
            .recorded_without_writer
            .is_empty()
    );
}
